import { describe, expect, it } from "vitest";
import { notificationDeliveryTimestampsEqual } from "../../notificationDeliveryTimestamp";

describe("notification lease timestamp identity", () => {
  it.each([
    ["2026-10-24T13:42:01.884Z", "2026-10-24T13:42:01.884000Z"],
    ["2026-10-24T13:42:01.884000Z", "2026-10-24T13:42:01.884Z"],
    ["2026-10-24T13:42:01.884Z", "2026-10-24T13:42:01.884000000Z"],
    ["2026-10-24T13:42:01Z", "2026-10-24T13:42:01.000000Z"],
    ["2026-10-24T13:42:01.884001Z", "2026-10-24T13:42:01.884001000Z"],
    ["2026-10-24T13:42:01.884000001Z", "2026-10-24T13:42:01.8840000010Z"],
    ["2026-10-24T13:42:01.884Z", "2026-10-24T14:42:01.884000+01:00"],
    ["2026-10-24T13:42:01.884Z", "2026-10-24T08:12:01.884000-05:30"],
    ["2026-01-01T00:00:01.884Z", "2025-12-31T19:00:01.884000-05:00"],
    ["2024-02-29T23:59:59.1Z", "2024-03-01T00:59:59.100000+01:00"],
    ["0001-01-01T00:00:00Z", "0000-12-31T19:00:00-05:00"],
    ["2026-10-24t13:42:01.884z", "2026-10-24T13:42:01.884000+00:00"],
  ])("accepts equivalent instants %s and %s", (left, right) => {
    expect(notificationDeliveryTimestampsEqual(left, right)).toBe(true);
  });

  it.each([
    ["2026-10-24T13:42:01.884Z", "2026-10-24T13:42:01.884001Z"],
    ["2026-10-24T13:42:01.884Z", "2026-10-24T13:42:01.884000001Z"],
    ["2026-10-24T13:42:01.884000001Z", "2026-10-24T13:42:01.884000002Z"],
    ["2026-10-24T13:42:01.8840000001Z", "2026-10-24T13:42:01.8840000002Z"],
    ["2026-10-24T13:42:01.884Z", "2026-10-24T13:42:02.884000Z"],
    ["2026-10-24T13:42:01.884Z", "2026-10-24T14:42:01.884000Z"],
    ["2026-10-24T13:42:01.884Z", "2026-10-24T13:42:01.884000+01:00"],
  ])("rejects distinct instants %s and %s", (left, right) => {
    expect(notificationDeliveryTimestampsEqual(left, right)).toBe(false);
  });

  it.each([
    null, "", "invalid", "2026-10-24", "2026-10-24 13:42:01Z", "2026-10-24T13:42:01",
    "2026-02-29T13:42:01Z", "2026-02-30T13:42:01Z", "2026-00-24T13:42:01Z", "2026-13-24T13:42:01Z",
    "2026-10-00T13:42:01Z", "2026-10-32T13:42:01Z", "2026-10-24T24:00:00Z", "2026-10-24T13:60:01Z",
    "2026-10-24T13:42:60Z", "2026-10-24T13:42:01.Z", "2026-10-24T13:42:01,884Z", "2026-10-24T13:42:01+24:00",
    "2026-10-24T13:42:01+00:60", "2026-10-24T13:42:01+0100", "2026-10-24T13:42:01Z ",
    "2026-10-24T13:42:01Z\n", "2026-10-24T13:42:01Z\r", "2026-10-24T13:42:01Z\r\n",
  ])("fails closed for invalid or unsupported timestamp %s", value => {
    expect(notificationDeliveryTimestampsEqual(value, value)).toBe(false);
    expect(notificationDeliveryTimestampsEqual(value, "2026-10-24T13:42:01Z")).toBe(false);
    expect(notificationDeliveryTimestampsEqual("2026-10-24T13:42:01Z", value)).toBe(false);
  });
});
